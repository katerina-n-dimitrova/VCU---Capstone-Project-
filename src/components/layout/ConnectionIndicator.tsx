import { useVehicleData } from '../../state/vehicleContext';
import { StatusPill } from '../common/StatusPill';
import { formatAge } from '../../utils/time';

/**
 * The link between this app and the vehicle, shown in the header on every page.
 * It describes the connection only — the vehicle's own state is on the pages.
 */
export function ConnectionIndicator() {
  const { connection, now, simulated } = useVehicleData();

  if (simulated) {
    return (
      <StatusPill tone="demo" title="All data on screen is generated by the simulator.">
        Simulated data
      </StatusPill>
    );
  }

  switch (connection.state) {
    case 'open':
      return (
        <StatusPill tone="normal" icon="wifi" title={connection.detail}>
          Connected
        </StatusPill>
      );
    case 'connecting':
      return (
        <StatusPill tone="information" icon="wifi" title={connection.detail}>
          Connecting
        </StatusPill>
      );
    case 'reconnecting':
      return (
        <StatusPill tone="warning" icon="wifi-off" title={connection.detail}>
          Reconnecting
        </StatusPill>
      );
    case 'error':
      return (
        <StatusPill tone="warning" icon="alert-triangle" title={connection.detail}>
          No data ({formatAge(connection.lastMessageAt, now)})
        </StatusPill>
      );
    default:
      return (
        <StatusPill tone="offline" title={connection.detail}>
          Not connected
        </StatusPill>
      );
  }
}
